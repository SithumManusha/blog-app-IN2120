/**
 * Pulse AI Blog Platform - Gemini AI Copilot Client
 * Live Summarization, Writing Copilot, and Auto-Tagging
 */

document.addEventListener('DOMContentLoaded', () => {
    initAISummarizer();
    initAICopilot();
});

// 1. Single Post Live Summarizer
function initAISummarizer() {
    const btn = document.getElementById('btn-generate-summary');
    const container = document.getElementById('summary-content');

    if (!btn || !container) return;

    btn.addEventListener('click', async () => {
        const postId = btn.getAttribute('data-post-id');
        const originalText = btn.innerHTML;
        btn.disabled = true;
        btn.innerHTML = `<i class="fa-solid fa-spinner fa-spin text-xs"></i> Analyzing with Gemini...`;

        try {
            const res = await fetch('?route=api.ai.summarize', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ post_id: postId })
            });

            const data = await res.json();
            if (data.success && data.summary) {
                container.innerHTML = data.summary.replace(/\n/g, '<br>');
                showToast(data.is_demo ? 'Generated demo summary. Set GEMINI_API_KEY for live AI!' : 'AI Summary generated successfully!', 'success');
            } else {
                showToast(data.error || 'Failed to generate summary.', 'error');
            }
        } catch (err) {
            showToast('Network error while contacting AI service.', 'error');
        } finally {
            btn.disabled = false;
            btn.innerHTML = `<i class="fa-solid fa-rotate text-[10px]"></i> Refresh Summary`;
        }
    });
}

// 2. Editor AI Copilot Tools
function initAICopilot() {
    const titleInput = document.getElementById('post-title');
    const contentInput = document.getElementById('post-content');
    const tagsInput = document.getElementById('post-tags');
    const summaryInput = document.getElementById('post-summary');

    // Helper to toggle button loading state
    function setButtonLoading(btn, loading, text) {
        if (!btn) return;
        if (loading) {
            btn.dataset.origHtml = btn.innerHTML;
            btn.disabled = true;
            btn.innerHTML = `<i class="fa-solid fa-spinner fa-spin text-[10px]"></i> ${text}`;
        } else {
            btn.disabled = false;
            btn.innerHTML = btn.dataset.origHtml || text;
        }
    }

    // A. Auto-Draft from Title
    const btnDraft = document.getElementById('btn-ai-draft');
    if (btnDraft) {
        btnDraft.addEventListener('click', async () => {
            const title = titleInput.value.trim();
            if (!title) {
                showToast('Please enter an Article Title first!', 'error');
                titleInput.focus();
                return;
            }

            setButtonLoading(btnDraft, true, 'Drafting...');
            try {
                const res = await fetch('?route=api.ai.copilot', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ action: 'generate_draft', text: title })
                });
                const data = await res.json();
                if (data.success && data.text) {
                    contentInput.value = data.text;
                    showToast('Draft generated by Gemini Copilot!', 'success');
                } else {
                    showToast(data.error || 'Failed to generate draft.', 'error');
                }
            } catch (err) {
                showToast('Error communicating with AI service.', 'error');
            } finally {
                setButtonLoading(btnDraft, false, 'Auto-Draft from Title');
            }
        });
    }

    // B. Fix Grammar & Tone
    const btnGrammar = document.getElementById('btn-ai-fix-grammar');
    if (btnGrammar) {
        btnGrammar.addEventListener('click', async () => {
            const text = contentInput.value.trim();
            if (!text) {
                showToast('Write some content first to fix grammar!', 'error');
                return;
            }

            setButtonLoading(btnGrammar, true, 'Polishing...');
            try {
                const res = await fetch('?route=api.ai.copilot', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ action: 'fix_grammar', text: text })
                });
                const data = await res.json();
                if (data.success && data.text) {
                    contentInput.value = data.text;
                    showToast('Grammar, tone, and formatting polished!', 'success');
                } else {
                    showToast(data.error || 'Failed to polish text.', 'error');
                }
            } catch (err) {
                showToast('Error communicating with AI service.', 'error');
            } finally {
                setButtonLoading(btnGrammar, false, 'Fix Grammar & Tone');
            }
        });
    }

    // C. Expand Draft
    const btnExpand = document.getElementById('btn-ai-expand');
    if (btnExpand) {
        btnExpand.addEventListener('click', async () => {
            const text = contentInput.value.trim();
            if (!text) {
                showToast('Write a draft section first to expand!', 'error');
                return;
            }

            setButtonLoading(btnExpand, true, 'Expanding...');
            try {
                const res = await fetch('?route=api.ai.copilot', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ action: 'expand', text: text })
                });
                const data = await res.json();
                if (data.success && data.text) {
                    contentInput.value = data.text;
                    showToast('Content expanded with rich insights!', 'success');
                } else {
                    showToast(data.error || 'Failed to expand content.', 'error');
                }
            } catch (err) {
                showToast('Error communicating with AI service.', 'error');
            } finally {
                setButtonLoading(btnExpand, false, 'Expand Draft');
            }
        });
    }

    // D. 5 Catchy Title Ideas
    const btnTitles = document.getElementById('btn-ai-catchy-titles');
    if (btnTitles) {
        btnTitles.addEventListener('click', async () => {
            const topic = titleInput.value.trim() || 'Software Engineering and Modern AI';
            setButtonLoading(btnTitles, true, 'Generating...');
            try {
                const res = await fetch('?route=api.ai.copilot', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ action: 'catchy_titles', text: topic })
                });
                const data = await res.json();
                if (data.success && data.text) {
                    alert("✨ 5 Catchy Title Suggestions:\n\n" + data.text);
                } else {
                    showToast(data.error || 'Failed to generate titles.', 'error');
                }
            } catch (err) {
                showToast('Error communicating with AI service.', 'error');
            } finally {
                setButtonLoading(btnTitles, false, 'AI Title Ideas');
            }
        });
    }

    // E. Auto-Suggest Tags
    const btnTags = document.getElementById('btn-ai-tags');
    if (btnTags) {
        btnTags.addEventListener('click', async () => {
            const content = contentInput.value.trim() || titleInput.value.trim();
            if (!content) {
                showToast('Please enter title or content first!', 'error');
                return;
            }

            setButtonLoading(btnTags, true, 'Tagging...');
            try {
                const res = await fetch('?route=api.ai.tags', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ content: content })
                });
                const data = await res.json();
                if (data.success && data.tags) {
                    tagsInput.value = data.tags;
                    showToast('Tags suggested successfully!', 'success');
                } else {
                    showToast(data.error || 'Failed to suggest tags.', 'error');
                }
            } catch (err) {
                showToast('Error contacting AI service.', 'error');
            } finally {
                setButtonLoading(btnTags, false, 'Auto-Tag');
            }
        });
    }

    // F. Pre-summarize in editor
    const btnPreSummary = document.getElementById('btn-ai-pre-summary');
    if (btnPreSummary) {
        btnPreSummary.addEventListener('click', async () => {
            const content = contentInput.value.trim();
            if (!content) {
                showToast('Write article content first to summarize!', 'error');
                return;
            }

            setButtonLoading(btnPreSummary, true, 'Summarizing...');
            try {
                const res = await fetch('?route=api.ai.summarize', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ content: content })
                });
                const data = await res.json();
                if (data.success && data.summary) {
                    summaryInput.value = data.summary;
                    showToast('Summary pre-generated for reader view!', 'success');
                } else {
                    showToast(data.error || 'Failed to generate summary.', 'error');
                }
            } catch (err) {
                showToast('Error contacting AI service.', 'error');
            } finally {
                setButtonLoading(btnPreSummary, false, 'Summarize');
            }
        });
    }
}
